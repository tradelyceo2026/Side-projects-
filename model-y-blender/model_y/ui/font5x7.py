WIDTH = 5
HEIGHT = 7

_CACHE: dict[str, list[list[int]]] = {}


def glyph(ch: str) -> list[list[int]]:
    """Rows of 0/1 for ``ch`` (uppercased, '?' when unknown)."""
    key = ch if ch in GLYPHS else ch.upper()
    if key not in GLYPHS:
        key = "?"
    cached = _CACHE.get(key)
    if cached is None:
        cached = [[1 if c == "1" else 0 for c in row] for row in GLYPHS[key].split("/")]
        _CACHE[key] = cached
    return cached


def text_width(text: str, scale: int = 1, tracking: int = 1) -> int:
    if not text:
        return 0
    return (WIDTH * scale + tracking * scale) * len(text) - tracking * scale


def text_height(scale: int = 1) -> int:
    return HEIGHT * scale


def validate() -> list[str]:
    """Return a list of malformed glyph names (used by the test-suite)."""
    bad = []
    for name, art in GLYPHS.items():
        rows = art.split("/")
        if len(rows) != HEIGHT or any(len(r) != WIDTH or set(r) - {"0", "1"} for r in rows):
            bad.append(name)
    return bad
